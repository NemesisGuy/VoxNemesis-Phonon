#!/usr/bin/env node
// Regenerates lib/voices.js from the Gradium voice catalog.
//
// The catalog lives at https://huggingface.co/gradium/phonon-voices (voices.jsonl, one JSON
// object per line). The browser build of phonon-tts cannot read that catalog itself: it
// resolves a voice name against the voices baked into a checkpoint, and the rest are added
// with `addVoice` from a URL. So the extension ships its own copy of the catalog and points
// `addVoice` at the file each entry names.
//
// Usage:
//   node scripts/fetch-assets.js            # regenerate lib/voices.js from the Hub
//   node scripts/fetch-assets.js --out X    # write somewhere else

const fs = require('fs');
const path = require('path');

const CATALOG_URL = 'https://huggingface.co/gradium/phonon-voices/resolve/main/voices.jsonl';
const VOICES_REPO = 'gradium/phonon-voices';

function parseArgs(argv) {
    const args = { out: path.join(__dirname, '..', 'lib', 'voices.js') };
    for (let i = 0; i < argv.length; i += 1) {
        if (argv[i] === '--out' && argv[i + 1]) {
            args.out = path.resolve(argv[i + 1]);
            i += 1;
        }
    }
    return args;
}

async function downloadCatalog() {
    const response = await fetch(CATALOG_URL);
    if (!response.ok) {
        throw new Error(`failed to fetch the voice catalog: HTTP ${response.status}`);
    }
    return response.text();
}

/** The catalog's lines, in the shape lib/voices.js stores them. */
function parseCatalog(text) {
    const voices = [];
    for (const line of text.split('\n')) {
        const trimmed = line.trim();
        if (!trimmed) continue;
        const entry = JSON.parse(trimmed);
        voices.push({
            name: entry.name,
            voice_id: entry.voice_id,
            filename: entry.filename,
            language: entry.language,
            locale: entry.locale,
            gender: entry.gender,
            age: entry.age,
            description: entry.description
        });
    }
    return voices;
}

function render(voices) {
    const header = `// Voice catalog — generated by scripts/fetch-assets.js, do not edit by hand.
//
// Source: ${CATALOG_URL}
// Every voice is a precomputed embedding the browser build loads on demand with
// 'addVoice'. The extension cannot clone a voice from a recording: the wasm build has no
// encoder for that.

const VOICE_CATALOG_REPO = '${VOICES_REPO}';
const VOICE_CATALOG_URL = '${CATALOG_URL}';

const VOICES = [
`;

    const body = voices
        .map((v) => `    ${JSON.stringify(v)},`)
        .join('\n');

    const footer = `
];

/** The URL of a catalog voice's file, pinned to no revision: the catalog's own file. */
function getVoiceUrl(filename) {
    return \`https://huggingface.co/\${VOICE_CATALOG_REPO}/resolve/main/\${filename}\`;
}

/** The catalog entry for a voice name, case- and accent-insensitively, or by voice id. */
function findVoice(name) {
    if (!name) return null;
    const needle = String(name).trim().toLowerCase();
    const flat = (s) => s.normalize('NFD').replace(/[\\u0300-\\u036f]/g, '').toLowerCase();
    return (
        VOICES.find((v) => v.name.toLowerCase() === needle) ||
        VOICES.find((v) => v.voice_id.toLowerCase() === needle) ||
        VOICES.find((v) => flat(v.name) === flat(needle)) ||
        null
    );
}

/** The catalog's voices for a language code, in catalog order. */
function getVoicesForLanguage(language) {
    if (!language || language === 'none') return VOICES.slice();
    return VOICES.filter((v) => v.language === language);
}

/** A short label for a voice: name, locale and gender. */
function describeVoice(voice) {
    if (!voice) return '';
    return \`\${voice.name} — \${voice.locale} \${voice.gender}\`;
}

export { VOICES, VOICE_CATALOG_REPO, VOICE_CATALOG_URL, getVoiceUrl, findVoice, getVoicesForLanguage, describeVoice };

// CommonJS compat for Jest tests
if (typeof module !== 'undefined' && module.exports) {
    module.exports = { VOICES, VOICE_CATALOG_REPO, VOICE_CATALOG_URL, getVoiceUrl, findVoice, getVoicesForLanguage, describeVoice };
}
`;

    return `${header}${body}${footer}`;
}

async function main() {
    const args = parseArgs(process.argv.slice(2));
    const text = await downloadCatalog();
    const voices = parseCatalog(text);
    if (voices.length === 0) throw new Error('the voice catalog came back empty');

    fs.mkdirSync(path.dirname(args.out), { recursive: true });
    fs.writeFileSync(args.out, render(voices), 'utf8');

    const languages = [...new Set(voices.map((v) => v.language))].sort();
    console.log(`Wrote ${voices.length} voices to ${args.out}`);
    console.log(`Languages: ${languages.join(', ')}`);
}

main().catch((err) => {
    console.error(err.message);
    process.exit(1);
});
